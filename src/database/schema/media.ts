import { sql } from 'drizzle-orm';
import {
  boolean,
  check,
  index,
  integer,
  pgTable,
  timestamp,
  uniqueIndex,
  uuid,
  varchar,
} from 'drizzle-orm/pg-core';
import { users } from './index';

const timestamps = () => ({
  createdAt: timestamp('created_at', { withTimezone: true })
    .defaultNow()
    .notNull(),
  updatedAt: timestamp('updated_at', { withTimezone: true })
    .defaultNow()
    .notNull(),
});

/**
 * Metadata for a file uploaded through `POST /media` and served back from
 * `GET /media/{id}`.
 *
 * The bytes live on disk under `MEDIA_ROOT`; this table is the only authority
 * for whether a stored file is reachable. `storage_key` is the path relative to
 * that root, generated by the server - a client never chooses it, so it cannot
 * traverse outside the root or overwrite another owner's file.
 *
 * `checksum_sha256` is recorded so a re-upload of identical bytes can be
 * recognised later without re-reading every file; it is not a uniqueness
 * constraint, because two owners legitimately storing the same picture must
 * keep independent rows they can each delete.
 */
export const mediaAssets = pgTable(
  'media_assets',
  {
    id: uuid('id').defaultRandom().primaryKey(),
    // Uploader. Kept after deletion of the asset so an audit trail survives.
    ownerUserId: uuid('owner_user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    purpose: varchar('purpose', { length: 32 }).notNull(),
    storageKey: varchar('storage_key', { length: 200 }).notNull(),
    contentType: varchar('content_type', { length: 64 }).notNull(),
    // Bytes are capped by MEDIA_MAX_BYTES (<= 20 MiB), so a 32-bit integer
    // holds the size exactly; no bigint->number precision loss is possible.
    byteSize: integer('byte_size').notNull(),
    checksumSha256: varchar('checksum_sha256', { length: 64 }).notNull(),
    originalFilename: varchar('original_filename', { length: 255 })
      .default('')
      .notNull(),
    width: integer('width'),
    height: integer('height'),
    // Migration 0013: camera metadata (GPS, device, timestamps) is stripped on
    // upload, so a photo of a stall does not publish the photographer's
    // location. Recorded because it changes the stored bytes.
    metadataStripped: boolean('metadata_stripped').default(false).notNull(),
    // Served from GET /media/{id}/thumbnail when a thumbnail was produced.
    thumbnailKey: varchar('thumbnail_key', { length: 200 }),
    // Moderation is a review state, never an automatic judgement. No provider
    // is integrated, so everything starts unreviewed until a human (or a future
    // provider) moves it.
    moderationStatus: varchar('moderation_status', { length: 16 })
      .default('unreviewed')
      .notNull(),
    // Soft delete: a row with deleted_at set is a tombstone that GET /media
    // refuses. The file on disk is left for an operator-driven cleanup pass.
    deletedAt: timestamp('deleted_at', { withTimezone: true }),
    ...timestamps(),
  },
  (table) => [
    uniqueIndex('media_assets_storage_key_unique').on(table.storageKey),
    index('media_assets_owner_created_idx').on(
      table.ownerUserId,
      table.createdAt,
    ),
    index('media_assets_purpose_created_idx').on(
      table.purpose,
      table.createdAt,
    ),
    check(
      'media_assets_purpose_check',
      sql`${table.purpose} in ('menu_item', 'tenant_logo', 'tenant_cover', 'avatar', 'case_evidence')`,
    ),
    check(
      'media_assets_content_type_check',
      sql`${table.contentType} in ('image/jpeg', 'image/png', 'image/webp')`,
    ),
    check(
      'media_assets_byte_size_check',
      sql`${table.byteSize} > 0 and ${table.byteSize} <= 20971520`,
    ),
    check(
      'media_assets_checksum_check',
      sql`${table.checksumSha256} ~ '^[0-9a-f]{64}$'`,
    ),
    check(
      'media_assets_moderation_check',
      sql`${table.moderationStatus} in ('unreviewed', 'clear', 'flagged')`,
    ),
    check(
      'media_assets_dimensions_check',
      // Both-or-neither, and positive when present. coalesce matters: a bare
      // `width > 0 and height > 0` evaluates to NULL for a half-filled pair,
      // and a CHECK passes on NULL - which would let width-only rows through.
      sql`(${table.width} is null and ${table.height} is null) or (coalesce(${table.width}, 0) > 0 and coalesce(${table.height}, 0) > 0)`,
    ),
  ],
);
